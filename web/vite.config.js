import { defineConfig } from 'vite'
import vue from '@vitejs/plugin-vue'
import { existsSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// The SPA is packaged into the daemon binary by `go:embed dist`. Built assets
// are content-hashed; index.html is served no-cache so a daemon upgrade is
// picked up on the next navigation.

// Development loop: `npm run dev` serves the SPA with HMR and forwards the
// same-origin surfaces it uses — /api, /healthz and the binary /ws WebSocket —
// to a simulator daemon (`capsulad -platform simulator`). The daemon keeps its
// real session semantics, and its self-signed certificate is accepted by the
// proxy only; the browser talks to the dev server.
const daemon = process.env.CAPSULA_WEB_TARGET || 'https://127.0.0.1:8443'

// The daemon's cookies are Secure + SameSite=Strict, so the dev server serves
// HTTPS itself when it can reuse the daemon's certificate (generated by
// `capsula auth init -hostname localhost -ip 127.0.0.1`). Safari does not treat
// plain http://localhost as a trustworthy origin for Secure cookies, so plain
// HTTP would silently drop the session. CAPSULA_DEV_HTTPS=0 forces HTTP;
// CAPSULA_DEV_SECURITY_DIR points at another `security/` directory.
const securityDir = process.env.CAPSULA_DEV_SECURITY_DIR ||
  fileURLToPath(new URL('../build/dev-web/security', import.meta.url))
const certPath = `${securityDir}/server.crt`
const keyPath = `${securityDir}/server.key`
const https = process.env.CAPSULA_DEV_HTTPS === '0' || !existsSync(certPath) || !existsSync(keyPath)
  ? undefined
  : { cert: readFileSync(certPath), key: readFileSync(keyPath) }

// `changeOrigin` stays false so the daemon's Origin/Host comparison still
// matches; only the browser-facing origin differs.
const proxy = { target: daemon, changeOrigin: false, secure: false }

export default defineConfig({
  plugins: [vue()],
  base: '/',
  server: {
    https,
    proxy: {
      '/api': proxy,
      '/healthz': proxy,
      '/ws': { ...proxy, ws: true }
    }
  },
  build: {
    outDir: '../internal/webui/dist',
    emptyOutDir: true,
    target: 'es2020',
    assetsInlineLimit: 0
  }
})
