// Command protogen emits the browser bindings for capsulad.web.v1 from the
// compiled Go descriptor. It is run after regenerating web.pb.go:
//
//	go run ./web/protogen
//
// The emitted module is checked in so the SPA builds without a protoc plugin.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"

	webv1 "capsulad/gen/go/capsulad/web/v1"
)

func main() {
	file := webv1.File_capsulad_web_v1_web_proto
	var js bytes.Buffer
	var ts bytes.Buffer

	fmt.Fprintln(&js, "// Code generated by web/protogen from proto/capsulad/web/v1/web.proto. DO NOT EDIT.")
	fmt.Fprintln(&js, `import { encodeMessage, decodeMessage } from "./runtime.js";`)
	fmt.Fprintln(&js)

	fmt.Fprintln(&ts, "// Code generated by web/protogen from proto/capsulad/web/v1/web.proto. DO NOT EDIT.")
	fmt.Fprintln(&ts)

	enums := sortedEnums(file)
	for _, e := range enums {
		name := string(e.Name())
		fmt.Fprintf(&js, "export const %s = Object.freeze({\n", name)
		fmt.Fprintf(&ts, "export declare const %s: Readonly<{\n", name)
		vals := e.Values()
		for i := range vals.Len() {
			v := vals.Get(i)
			fmt.Fprintf(&js, "  %s: %d,\n", v.Name(), v.Number())
			fmt.Fprintf(&ts, "  readonly %s: %d;\n", v.Name(), v.Number())
		}
		fmt.Fprintln(&js, "});")
		fmt.Fprintf(&ts, "}>;\nexport type %sValue = number;\n\n", name)
	}
	fmt.Fprintln(&js)
	fmt.Fprintln(&js, "export const EnumNames = Object.freeze({")
	fmt.Fprintln(&ts, "export declare const EnumNames: Readonly<Record<string, readonly string[]>>;")
	for _, e := range enums {
		vals := e.Values()
		names := make([]string, 0, vals.Len())
		for i := range vals.Len() {
			names = append(names, fmt.Sprintf("%q", string(vals.Get(i).Name())))
		}
		fmt.Fprintf(&js, "  %q: [%s],\n", e.FullName(), strings.Join(names, ", "))
	}
	fmt.Fprintln(&js, "});")
	fmt.Fprintln(&js)

	messages := sortedMessages(file)
	fmt.Fprintln(&js, "export const SCHEMA = Object.freeze({")
	for _, m := range messages {
		fmt.Fprintf(&js, "  %q: { name: %q, fields: [\n", m.FullName(), m.FullName())
		fields := m.Fields()
		for i := range fields.Len() {
			fmt.Fprintf(&js, "    %s,\n", jsField(fields.Get(i)))
		}
		fmt.Fprintln(&js, "  ] },")
	}
	fmt.Fprintln(&js, "});")
	fmt.Fprintln(&js)

	consts := make([]string, 0, len(messages))
	for _, m := range messages {
		consts = append(consts, fmt.Sprintf("%s: %q", m.Name(), m.FullName()))
	}
	fmt.Fprintf(&js, "const TYPE = { %s };\n\n", strings.Join(consts, ", "))

	fmt.Fprint(&js, `export function encode(typeName, obj) {
  return encodeMessage(SCHEMA, typeName, obj || {});
}

export function decode(typeName, bytes) {
  return decodeMessage(SCHEMA, typeName, bytes);
}
`)

	for _, m := range messages {
		name := string(m.Name())
		fmt.Fprintf(&js, "export const %s = {\n", name)
		fmt.Fprintf(&js, "  type: \"%s\",\n", m.FullName())
		fmt.Fprintf(&js, "  encode(obj) { return encodeMessage(SCHEMA, TYPE.%s, obj || {}); },\n", name)
		fmt.Fprintf(&js, "  decode(bytes) { return decodeMessage(SCHEMA, TYPE.%s, bytes); },\n", name)
		fmt.Fprintln(&js, "};")
	}

	fmt.Fprintln(&ts, "export function encode(typeName: string, obj: unknown): Uint8Array;")
	fmt.Fprintln(&ts, "export function decode(typeName: string, bytes: Uint8Array): unknown;")
	fmt.Fprintln(&ts, "export declare const SCHEMA: Readonly<Record<string, unknown>>;")
	fmt.Fprintln(&ts)

	for _, m := range messages {
		name := string(m.Name())
		fmt.Fprintf(&ts, "export interface %s {\n", name)
		fields := m.Fields()
		for i := range fields.Len() {
			f := fields.Get(i)
			fmt.Fprintf(&ts, "  %s?: %s;\n", f.JSONName(), tsType(f))
		}
		fmt.Fprintln(&ts, "}")
		fmt.Fprintf(&ts, "export declare const %s: {\n  readonly type: string;\n  encode(obj: %s): Uint8Array;\n  decode(bytes: Uint8Array): %s;\n};\n\n", name, name, name)
	}

	if err := os.WriteFile(filepath.Join("web", "src", "proto", "web_pb.js"), js.Bytes(), 0o644); err != nil {
		fail(err)
	}
	if err := os.WriteFile(filepath.Join("web", "src", "proto", "web_pb.d.ts"), ts.Bytes(), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "protogen:", err)
	os.Exit(1)
}

func sortedMessages(file protoreflect.FileDescriptor) []protoreflect.MessageDescriptor {
	msgs := file.Messages()
	out := make([]protoreflect.MessageDescriptor, 0, msgs.Len())
	for i := range msgs.Len() {
		out = append(out, msgs.Get(i))
	}
	sort.Slice(out, func(i, j int) bool { return out[i].FullName() < out[j].FullName() })
	return out
}

func sortedEnums(file protoreflect.FileDescriptor) []protoreflect.EnumDescriptor {
	enums := file.Enums()
	out := make([]protoreflect.EnumDescriptor, 0, enums.Len())
	for i := range enums.Len() {
		out = append(out, enums.Get(i))
	}
	sort.Slice(out, func(i, j int) bool { return out[i].FullName() < out[j].FullName() })
	return out
}

func kindOf(f protoreflect.FieldDescriptor) string {
	switch f.Kind() {
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BoolKind:
		return "bool"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "uint64"
	case protoreflect.FloatKind:
		return "float"
	case protoreflect.DoubleKind:
		return "double"
	case protoreflect.EnumKind:
		return "enum"
	case protoreflect.MessageKind:
		return "message"
	default:
		return "unsupported:" + f.Kind().String()
	}
}

func jsField(f protoreflect.FieldDescriptor) string {
	name := f.JSONName()
	if f.IsMap() {
		entry := f.Message()
		key := entry.Fields().ByNumber(1)
		val := entry.Fields().ByNumber(2)
		keyKind := kindOf(key)
		valKind := kindOf(val)
		valType := ""
		if valKind == "message" {
			valType = fmt.Sprintf(", valueType: %q", val.Message().FullName())
		}
		return fmt.Sprintf("{ no: %d, name: %q, kind: \"map\", keyKind: %q, valueKind: %q%s }",
			f.Number(), name, keyKind, valKind, valType)
	}
	parts := []string{fmt.Sprintf("no: %d", f.Number()), fmt.Sprintf("name: %q", name), fmt.Sprintf("kind: %q", kindOf(f))}
	if f.IsList() {
		parts = append(parts, "repeated: true")
	}
	if f.Kind() == protoreflect.MessageKind {
		parts = append(parts, fmt.Sprintf("type: %q", f.Message().FullName()))
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

func tsType(f protoreflect.FieldDescriptor) string {
	if f.IsMap() {
		entry := f.Message()
		val := entry.Fields().ByNumber(2)
		return fmt.Sprintf("{ [key: string]: %s }", tsScalar(val))
	}
	base := tsScalar(f)
	if f.IsList() {
		return base + "[]"
	}
	return base
}

func tsScalar(f protoreflect.FieldDescriptor) string {
	switch f.Kind() {
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BoolKind:
		return "boolean"
	case protoreflect.FloatKind, protoreflect.DoubleKind:
		return "number"
	case protoreflect.EnumKind:
		return "number"
	case protoreflect.MessageKind:
		return string(f.Message().Name())
	default:
		return "number"
	}
}
